function placeholder(name: string, layer: string, tcpLayer: string, ports: string): ProtocolContent {
  return {
    title: name,
    whatItIs: `${name} é um protocolo de rede. Conteúdo detalhado em breve.`,
    osiLayer: layer, tcpIpLayer: tcpLayer, ports,
    realLife: 'Exemplos detalhados em breve.',
    securityRisks: 'Considerações de segurança em documentação.',
    wiresharkFilter: name.toLowerCase().replace(/[^a-z]/g, ''),
    wiresharkTip: 'Detalhes do filtro em breve.',
    commands: [{ command: `# Comandos ${name} em breve`, explanation: 'Exemplos em preparação.' }],
    keyTakeaways: [`${name} é um protocolo importante`, 'Mais detalhes serão adicionados'],
    quiz: [
      { question: `${name} é um protocolo de rede.`, type: 'true-false', options: ['Verdadeiro', 'Falso'], correctAnswer: 'Verdadeiro' },
      { question: `Em qual camada opera o ${name}?`, type: 'multiple-choice', options: [layer, 'Camada 1', 'Camada 2', 'Camada 6'], correctAnswer: layer },
      { question: `${name} usa criptografia por padrão.`, type: 'true-false', options: ['Verdadeiro', 'Falso'], correctAnswer: 'Falso' },
      { question: `Quais são as portas do ${name}?`, type: 'multiple-choice', options: [ports, 'TCP 80', 'UDP 53', 'TCP 22'], correctAnswer: ports },
      { question: `Entender ${name} é importante para segurança.`, type: 'true-false', options: ['Verdadeiro', 'Falso'], correctAnswer: 'Verdadeiro' },
    ],
  };
}

